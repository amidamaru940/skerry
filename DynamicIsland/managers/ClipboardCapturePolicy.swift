import AppKit

/// Decides whether a clipboard change may enter the history.
enum ClipboardCapturePolicy {
    enum Decision: Equatable {
        case record
        case paused
        /// The pasteboard carries a marker that password managers and similar
        /// tools put on secrets and throwaway copies (see nspasteboard.org).
        case concealed
        /// The copy was made in an app the user asked to ignore.
        case ignoredApp
        /// Written by Skerry itself (see ClipboardOwnWrites).
        case ownWrite
        /// A clipboard screenshot, collected by the Screenshots tab instead.
        case routedToScreenshots
    }

    static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("com.typeit4me.clipping"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("Pasteboard generator type"),
    ]

    /// Password managers whose copies are never recorded, by bundle identifier.
    static let defaultIgnoredApps = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.1password.1password",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
    ]

    static func decide(
        types: [NSPasteboard.PasteboardType],
        sourceBundleID: String?,
        isPaused: Bool,
        ignoredApps: [String]
    ) -> Decision {
        if isPaused { return .paused }
        if types.contains(where: concealedTypes.contains) { return .concealed }
        if let sourceBundleID, ignoredApps.contains(sourceBundleID) { return .ignoredApp }
        return .record
    }

    /// Every type on the pasteboard, across all of its items: a marker may sit
    /// on any item, not only the first one that `NSPasteboard.types` reports.
    static func allTypes(on pasteboard: NSPasteboard) -> [NSPasteboard.PasteboardType] {
        var types = pasteboard.types ?? []
        for item in pasteboard.pasteboardItems ?? [] {
            types.append(contentsOf: item.types)
        }
        return types
    }
}
